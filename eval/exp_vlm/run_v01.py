#!/usr/bin/env python3
"""GRID.V01 -- reading check: can the model read our contact sheet, tile by tile?

20 pre-registered windows, ONE `read_tiles` call each (cap 160 image calls).
This is a READING measurement only.  It says nothing about whether the model's
judgement is any good; that is V02/V03.  A human spot check of the sheets is the
builder's job and is OUTSTANDING until they do it.

Metrics, all against OUR builder's sidecar (the ground truth, not the model):
  * exact match  -- returned tile number AND timestamp both match the sidecar label;
  * coverage     -- how many of the 12 tiles got a line at all;
  * per returned line and per sheet tile, because the two answer different questions.

Run: python3 eval/exp_vlm/run_v01.py [--limit N]
"""
from __future__ import annotations

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
for p in (ROOT, os.path.join(ROOT, "tools", "dsh"), os.path.join(ROOT, "eval")):
    if p not in sys.path:
        sys.path.insert(0, p)

import common as C  # noqa: E402
import vlm_mosaic as VM  # noqa: E402
from eval.exp_vlm import vlm_common as V  # noqa: E402
from eval.exp_vlm import vlm_run as R  # noqa: E402

#: The frozen PREREG sets V01's budget to 20 calls.  The task brief said "cap 160"
#: (a discrepancy recorded in docs/reports/grid_vlm_b.md); 20 calls satisfy both.
CAP = R.PREREG["call_budget"]["V01"]
IDS = R.PREREG["windows"]["V01_20"]
OUT = os.path.join(ROOT, "eval", "results", "exp_vlm", "GRID.V01.json")
LEDGER = os.environ.get("JADAL_VLM_LEDGER", "/tmp/opencode/dsh/vlm_ledger_b.jsonl")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=0)
    args = ap.parse_args()

    rows = {r["window"]: r for r in V.ood_windows()}
    ids = IDS[:args.limit] if args.limit else IDS
    already = R.done_pairs(LEDGER)

    for wid in ids:
        if (wid, "v01_read_tiles") in already:
            print(f"{wid}: already in ledger, skipping (no call spent)", flush=True)
            continue
        win = rows[wid]
        png, doc = R.sheet_for_window(win, tag="v01_")
        R.guard(LEDGER, CAP, 1)
        rec = VM.ask(png, "read_tiles", ledger=LEDGER,
                     extra={"window": wid, "arm": "v01_read_tiles",
                            "y": win["y"], "factory": win["factory"],
                            "reason": win["reason"], "sheet_sha": doc["png_sha256"],
                            "n_tiles": doc["n_tiles"], "cols": doc["cols"],
                            "labels": doc["labels"]})
        m = R.read_tiles_metrics(rec.get("tiles") or {}, doc["tiles"])
        print(f"{wid}: ok={rec['ok']} lines={m['n_returned_lines']} "
              f"coverage={m['tile_coverage_rate']} exact/sheet={m['exact_match_rate_per_sheet_tile']} "
              f"({rec.get('seconds')}s)", flush=True)

    # ---- aggregate from the ledger (source of truth for what was spent) ----
    recs = [r for r in R.ledger_rows(LEDGER) if r.get("arm") == "v01_read_tiles"]
    per_window = []
    for r in recs:
        sc_path = os.path.join(V.SHEET_DIR, f"v01_{r['window']}_n12_c4_l1_sNone.json")
        side = json.load(open(sc_path)) if os.path.exists(sc_path) else None
        m = R.read_tiles_metrics(r.get("tiles") or {}, side["tiles"]) if side else {}
        per_window.append({
            "window": r["window"], "factory": r.get("factory"), "y": r.get("y"),
            "reason": r.get("reason"), "ok": r.get("ok"), "seconds": r.get("seconds"),
            "sheet_sha256": r.get("sheet_sha"), "prompt_sha256": r.get("prompt_sha256"),
            "model_id": r.get("model_id"), "error": r.get("error"),
            "metrics": {k: v for k, v in m.items() if k != "per_tile"},
            "raw_reply": r.get("raw"),
        })

    ok = [w for w in per_window if w["ok"]]
    tot_tiles = sum(w["metrics"].get("n_expected_tiles", 0) for w in ok)
    tot_lines = sum(w["metrics"].get("n_returned_lines", 0) for w in ok)
    tot_cov = sum(w["metrics"].get("n_tiles_covered", 0) for w in ok)
    tot_exact = sum(w["metrics"].get("n_exact_number_and_timestamp", 0) for w in ok)
    calls = VM.count_calls(LEDGER)

    payload = {
        "id": "GRID.V01", "status": "done",
        "n": len(ok), "n_bad": sum(1 for w in ok if w["y"] == 0),
        "n_good": sum(1 for w in ok if w["y"] == 1),
        "n_failed_calls": sum(1 for w in per_window if not w["ok"]),
        "label_source": "reading measurement against OUR builder's sidecar label table; "
                        "no human label is used and no quality claim is made",
        "protocol": "20 pre-registered V01 windows, ONE read_tiles call each on the default "
                    "12-tile 4x3 426x240 labelled sheet; tile number AND timestamp compared "
                    "with the sidecar generated by tools/dsh/vlm_sheet.py (ground truth)",
        "model_id": VM.MODEL_ID, "model_label": VM.MODEL_LABEL,
        "prompt": "read_tiles", "prompt_sha256": VM.PROMPT_SHA256["read_tiles"],
        "sheet_version": "vlm-sheet-1.0.0",
        "exact_match_rate_per_sheet_tile": (round(tot_exact / tot_tiles, 4) if tot_tiles else None),
        "exact_match_rate_per_returned_line": (round(tot_exact / tot_lines, 4) if tot_lines else None),
        "tile_coverage_rate": (round(tot_cov / tot_tiles, 4) if tot_tiles else None),
        "counts": {"sheet_tiles": tot_tiles, "returned_lines": tot_lines,
                   "tiles_covered": tot_cov, "exact_number_and_timestamp": tot_exact},
        "per_window": per_window,
        "ci95": None,
        "ci95_type": "not applicable: V01 is a descriptive reading measurement (no AUROC, "
                     "no classifier, no hypothesis test)",
        "device": "API call (OpenCode Go Responses, model read in-process); sheets built on CPU",
        "cost": f"{len([r for r in R.ledger_rows(LEDGER) if r.get('arm') == 'v01_read_tiles'])} "
                f"image API calls made by V01 (PREREG cap {CAP}; the task brief said 160 -- "
                f"both satisfied); {calls['text']} text calls",
        "command": "JADAL_VLM_LEDGER=<ledger> python3 eval/exp_vlm/run_v01.py",
        "git_sha": C.git_sha(), "seed": 0,
        "config_sha256": C.config_sha256({"windows": IDS, "cap": CAP, "n_tiles": 12, "cols": 4,
                                          "labels": True, "prompt": "read_tiles",
                                          "prompt_sha256": VM.PROMPT_SHA256["read_tiles"]}),
        "config": {"windows": IDS, "cap": CAP, "n_tiles": 12, "cols": 4, "labels": True,
                   "prompt": "read_tiles"},
        "human_spot_check": "OUTSTANDING -- the builder must eyeball the sheets and replies; "
                            "sheet PNG sha256 and full raw replies are included for that purpose. "
                            "PNGs live under /tmp/opencode/dsh/sheets and are never committed.",
        "interpretation_limits": [
            "READING, not quality: a model that reads every tile perfectly can still judge badly.",
            "One call per window: no run-to-run variance is measured here (that is V04).",
            "The model is probabilistic; a correct read is not a guarantee of a correct read next time.",
            "Timestamps come from the same read_tiles reply; no separate timestamp prompt was added, "
            "so a wrong timestamp and a wrong tile number are not separated by a second question.",
        ],
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    C.save_results(OUT, payload)
    print(json.dumps({k: payload[k] for k in
                      ("n", "n_failed_calls", "exact_match_rate_per_sheet_tile",
                       "exact_match_rate_per_returned_line", "tile_coverage_rate",
                       "counts", "cost")}, indent=1))
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
